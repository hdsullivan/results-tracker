def test_import_csv_cli(tmp_path):
    db = str(tmp_path / "r.db")
    csv = tmp_path / "r.csv"
    csv.write_text("method,dataset,seed,lambda,psnr\nTV,Set12,0,0.1,27.5\nOurs,Set12,0,0.1,31.2\n")
    r = runner.invoke(app, ["import", str(csv), "-e", "cmp", "--config-col", "lambda", "--dry-run", "--db", db])
    assert r.exit_code == 0, r.output
    assert "2 rows" in r.output and "would import 2" in r.output
    r = runner.invoke(app, ["import", str(csv), "-e", "cmp", "--config-col", "lambda", "--db", db])
    assert r.exit_code == 0, r.output
    assert "imported 2" in r.output
    r = runner.invoke(app, ["import", str(csv), "-e", "cmp", "--config-col", "lambda", "--db", db])
    assert "imported 0, skipped 2" in r.output
    r = runner.invoke(app, ["table", "-e", "cmp", "--db", db])
    assert r.exit_code == 0 and "Ours" in r.output and "31.20" in r.output


def test_export_commands(tmp_path):
    db = str(tmp_path / "r.db")
    assert runner.invoke(app, ["demo", "--db", db]).exit_code == 0
    out = tmp_path / "tab.tex"
    r = runner.invoke(app, ["export", "table", "-e", "main-comparison", "--label", "tab:main", "-o", str(out), "--db", db])
    assert r.exit_code == 0, r.output
    tex = out.read_text()
    assert "\\begin{tabular}" in tex and "\\multicolumn{3}{c}{Set12}" in tex and "TV [1]" in tex and "\\label{tab:main}" in tex
    assert "Generated by results-tracker" in tex
    # stdout when no -o, bare tabular
    r = runner.invoke(app, ["export", "table", "-e", "main-comparison", "--cols", "none", "--env", "none", "--db", db])
    assert r.exit_code == 0 and "% Generated by results-tracker" in r.output and "\\begin{table}" not in r.output
    assert "n varies" in r.output  # the reported-only DPIR row has n=1 -> audit warning on stderr
    r = runner.invoke(app, ["export", "ablation-table", "-e", "ablation", "--db", db])
    assert r.exit_code == 0 and "\\checkmark" in r.output and "Full model" in r.output
    r = runner.invoke(app, ["export", "sweep-table", "-e", "lambda-sweep", "--param", "lambda", "--metric", "psnr",
                            "--param-label", "$\\lambda$", "--db", db])
    assert r.exit_code == 0 and "$\\lambda$ & PSNR" in r.output
    for args, name in [
        (["sweep-fig", "-e", "lambda-sweep", "--param", "lambda", "--metric", "psnr", "--png"], "sweep.pdf"),
        (["ablation-fig", "-e", "ablation", "--metric", "psnr"], "abl.pdf"),
        (["comparison-fig", "-e", "main-comparison", "--metric", "psnr", "--emphasize", "Ours"], "cmp.pdf"),
    ]:
        p = tmp_path / name
        r = runner.invoke(app, ["export", *args, "-o", str(p), "--db", db])
        assert r.exit_code == 0, r.output
        assert p.exists() and p.stat().st_size > 1000
    assert (tmp_path / "sweep.png").exists()
    r = runner.invoke(app, ["export", "runs-csv", "-e", "main-comparison", "--db", db])
    assert r.exit_code == 0
    lines = r.output.strip().splitlines()
    assert lines[0].startswith("run_id,experiment,method") and "metric.psnr" in lines[0] and len(lines) == 20
    r = runner.invoke(app, ["export", "table", "-e", "nope", "--db", db])
    assert r.exit_code == 1


def test_demo_is_idempotent_and_reset(tmp_path):
    db = str(tmp_path / "r.db")
    art = tmp_path / "art"
    r = runner.invoke(app, ["demo", "--db", db, "--artifacts", str(art)])
    assert r.exit_code == 0, r.output
    assert (art / "main-comparison" / "Ours_Set12_seed0" / "reconstruction.png").exists()
    n1 = len(runner.invoke(app, ["runs", "-n", "1000", "--db", db]).output.splitlines())
    r = runner.invoke(app, ["demo", "--db", db])
    assert r.exit_code == 0 and "already exists" in r.output
    assert len(runner.invoke(app, ["runs", "-n", "1000", "--db", db]).output.splitlines()) == n1
    r = runner.invoke(app, ["demo", "--db", db, "--reset"])
    assert r.exit_code == 0 and "deleted" in r.output and "seeded" in r.output
    # audit sees the reported-only baseline as a missing cell, sweep has one failed run
    r = runner.invoke(app, ["export", "table", "-e", "main-comparison", "--db", db])
    assert "missing: method=DPIR, dataset=CBSD68" in r.output
    r = runner.invoke(app, ["sweep", "-e", "lambda-sweep", "--param", "lambda", "--metric", "psnr", "--db", db])
    assert r.exit_code == 0 and "│ 2 │" in r.output  # lambda=1.0 has n=2


def test_export_visual_cli(tmp_path):
    db = str(tmp_path / "r.db")
    art = tmp_path / "art"
    assert runner.invoke(app, ["demo", "--db", db, "--artifacts", str(art)]).exit_code == 0
    out = tmp_path / "vis.png"
    r = runner.invoke(app, ["export", "visual", "-e", "main-comparison", "-d", "Set12", "--seed", "0",
                            "--reference", "ground_truth.png", "--measurement", "measurement.png",
                            "--zoom", "--tex", "-o", str(out), "--db", db])
    assert r.exit_code == 0, r.output
    assert out.exists() and out.with_suffix(".json").exists() and out.with_suffix(".tex").exists()
    assert "Left to right: Reference, Measurement, TV [1], PnP-BM3D [2], Ours" in r.output
    assert "Yellow box" in r.output and "figure*" in out.with_suffix(".tex").read_text()
    # error mode and rows by seed
    r = runner.invoke(app, ["export", "visual", "-e", "main-comparison", "-d", "Set12", "--reference", "ground_truth.png",
                            "--measurement", "measurement.png", "--mode", "error", "--rows", "seed",
                            "-o", str(tmp_path / "err.png"), "--db", db])
    assert r.exit_code == 0, r.output
    assert "Rows: $seed = 0$, $seed = 1$, $seed = 2$" in r.output and "luminance" in r.output
    # DPIR (reported, no artifacts) is named as omitted, not silently dropped
    assert "not shown:" in r.output and "DPIR" in r.output and "no artifacts_dir" in r.output
    r = runner.invoke(app, ["export", "sweep-fig", "-e", "lambda-sweep", "--param", "lambda", "--metric", "psnr",
                            "--tex", "-o", str(tmp_path / "s.pdf"), "--db", db])
    assert r.exit_code == 0 and (tmp_path / "s.tex").read_text().startswith("\\begin{figure}[!t]")
    r = runner.invoke(app, ["export", "preamble"])
    assert r.exit_code == 0 and "booktabs" in r.output


def test_export_bundle_cli(tmp_path):
    db = str(tmp_path / "r.db")
    assert runner.invoke(app, ["demo", "--db", db, "--artifacts", str(tmp_path / "art")]).exit_code == 0
    out = tmp_path / "b.zip"
    r = runner.invoke(app, ["export", "bundle", "-p", "demo-paper", "-o", str(out), "--db", db])
    assert r.exit_code == 0, r.output
    assert out.exists() and out.stat().st_size > 10_000
    assert "wrote" in r.output and "20 files" in r.output
    r = runner.invoke(app, ["export", "bundle", "-p", "nope", "--db", db])
    assert r.exit_code == 1
    # visual with guessed roles (no --image/--reference given)
    r = runner.invoke(app, ["export", "visual", "-e", "main-comparison", "-d", "Set12", "--seed", "0", "--zoom",
                            "-o", str(tmp_path / "v.png"), "--db", db])
    assert r.exit_code == 0, r.output
    assert "Left to right: Reference, Measurement, TV [1], PnP-BM3D [2], Ours" in r.output
