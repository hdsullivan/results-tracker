r"""booktabs LaTeX tables generated from aggregated results.

Conventions (from the lab's IEEE table checklist):
- rankings use unrounded means; display rounding happens only here;
- bold = best in the valid comparison group (one column), underline = second;
- missing cells are rendered as `--` and listed in a comment header;
- units and direction arrows live in the header;
- the .tex carries a provenance comment; never edit generated numbers by hand.

Requires `\usepackage{booktabs}`; ablation tables also use `\checkmark` (amssymb).
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Mapping, Optional, Sequence

from .. import aggregate as agg

MetricDefs = Mapping[str, Mapping[str, Any]]  # name -> {"unit", "higher_is_better", "fmt"}

_ESCAPES = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "$": r"\$", "{": r"\{", "}": r"\}"}
# Unicode that pdflatex cannot digest, as produced by describe_diff and friends.
_UNICODE = {"→": r"$\rightarrow$", "←": r"$\leftarrow$", "±": r"$\pm$", "×": r"$\times$", "Δ": r"$\Delta$",
            "✓": r"\checkmark", "✗": r"$\times$", "−": r"$-$", "↑": r"$\uparrow$", "↓": r"$\downarrow$"}


def latex_escape(text: Any) -> str:
    """Escape LaTeX specials and common Unicode symbols, unless the string already looks like LaTeX
    (contains a backslash), in which case it is passed through untouched."""
    s = str(text)
    if "\\" in s:
        return s
    return "".join(_UNICODE.get(ch, _ESCAPES.get(ch, ch)) for ch in s)


def fmt_number(value: float, fmt: str = ".2f") -> str:
    s = format(value, fmt)
    return f"$-${s[1:]}" if s.startswith("-") else s


def fmt_signed(value: float, fmt: str = ".2f") -> str:
    s = format(value, f"+{fmt}")
    return f"$-${s[1:]}" if s.startswith("-") else f"$+${s[1:]}"


def fmt_stat(st: Optional[agg.Stat], fmt: str, std: str = "pm") -> str:
    """std: 'pm' -> 30.96 $\\pm$ 0.39 ; 'small' -> 30.96 {\\scriptsize$\\pm$0.39} ; 'none' -> 30.96."""
    if st is None:
        return "--"
    m = fmt_number(st.mean, fmt)
    if std == "none" or st.n < 2:
        return m
    sd = format(st.std, fmt)
    if std == "small":
        return f"{m} {{\\scriptsize$\\pm${sd}}}"
    return f"{m} $\\pm$ {sd}"


def display_metric_name(metric: str, names: Optional[Mapping[str, str]] = None) -> str:
    """Explicit mapping wins; short lowercase names (psnr, ssim) are upper-cased; the rest stay as is."""
    if names and metric in names:
        return names[metric]
    if metric.islower() and len(metric) <= 5 and "_" not in metric:
        return metric.upper()
    return metric


def metric_header(metric: str, defs: MetricDefs, names: Optional[Mapping[str, str]] = None, arrows: bool = True) -> str:
    d = defs.get(metric, {})
    name = latex_escape(display_metric_name(metric, names))
    if d.get("unit"):
        name += f" ({latex_escape(d['unit'])})"
    if arrows:
        name += r" $\uparrow$" if d.get("higher_is_better", True) else r" $\downarrow$"
    return name


def _highlight(s: str, best: bool, second: bool, underline_second: bool) -> str:
    if best:
        return f"\\textbf{{{s}}}"
    if second and underline_second:
        return f"\\underline{{{s}}}"
    return s


def _wrap(
    tabular: str,
    *,
    env: Optional[str],
    caption: Optional[str],
    label: Optional[str],
    font: Optional[str],
    position: str,
    provenance: Optional[str],
) -> str:
    lines = []
    if provenance:
        lines += [f"% {ln}" for ln in provenance.splitlines()]
    if env:
        lines.append(f"\\begin{{{env}}}[{position}]")
        lines.append("\\centering")
        if caption:
            lines.append(f"\\caption{{{caption}}}")
        if label:
            lines.append(f"\\label{{{label}}}")
    if font:
        lines.append(f"\\{font}")
    lines.append(tabular)
    if env:
        lines.append(f"\\end{{{env}}}")
    return "\n".join(lines) + "\n"


def provenance_note(source: str, experiment: str, n_runs: int, extra: str = "") -> str:
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    note = f"Generated by results-tracker on {stamp} from {source}, experiment '{experiment}', {n_runs} runs."
    note += "\nDo not edit numbers by hand; regenerate from the database."
    if extra:
        note += "\n" + extra
    return note


# --------------------------------------------------------------------------- comparison

def comparison_latex(
    pt: agg.PivotTable,
    defs: MetricDefs,
    *,
    caption: Optional[str] = None,
    label: Optional[str] = None,
    env: Optional[str] = "table",
    position: str = "!t",
    font: Optional[str] = None,
    std: str = "pm",
    underline_second: bool = True,
    row_labels: Optional[Mapping[Any, str]] = None,
    col_labels: Optional[Mapping[Any, str]] = None,
    metric_names: Optional[Mapping[str, str]] = None,
    row_header: Optional[str] = None,
    audit: Optional[agg.GridAudit] = None,
    provenance: Optional[str] = None,
) -> str:
    """Methods as rows; (column group x metric) as columns; bold best / underline second per column."""
    nm = len(pt.metrics)
    ncols = len(pt.cols) * nm
    colspec = "l" + " " + " ".join("c" * nm for _ in pt.cols)
    out = ["\\begin{tabular}{" + colspec + "}", "\\toprule"]

    grouped = pt.col_key is not None and not (len(pt.cols) == 1 and pt.cols[0] is None)
    if grouped:
        heads = [""]
        rules = []
        for i, c in enumerate(pt.cols):
            lab = latex_escape((col_labels or {}).get(c, c))
            heads.append(f"\\multicolumn{{{nm}}}{{c}}{{{lab}}}")
            a, b = 2 + i * nm, 1 + (i + 1) * nm
            rules.append(f"\\cmidrule(lr){{{a}-{b}}}")
        out.append(" & ".join(heads) + " \\\\")
        out.append(" ".join(rules))
    head = [latex_escape(row_header or pt.row_key.capitalize())]
    for _ in pt.cols:
        head += [metric_header(m, defs, metric_names) for m in pt.metrics]
    out.append(" & ".join(head) + " \\\\")
    out.append("\\midrule")

    for r in pt.rows:
        cells = [latex_escape((row_labels or {}).get(r, r))]
        for c in pt.cols:
            for m in pt.metrics:
                st = pt.stat(r, c, m)
                s = fmt_stat(st, defs.get(m, {}).get("fmt", ".2f"), std)
                if st is not None:
                    s = _highlight(s, pt.is_best(r, c, m), pt.is_second(r, c, m), underline_second)
                cells.append(s)
        out.append(" & ".join(cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]

    if caption is None:
        caption = default_comparison_caption(pt, defs, std, underline_second)
    notes = []
    if audit and (audit.missing or audit.failed or audit.coverage):
        notes.append("Audit: " + audit.summary() + ("." if not audit.missing else ". Missing cells rendered as --."))
        for m in audit.missing[:20]:
            notes.append("  missing: " + ", ".join(f"{k}={v}" for k, v in zip(audit.keys, m)))
        for c in audit.coverage:
            notes.append("  WARNING rows pooled over different " + c)
    prov = provenance + ("\n" + "\n".join(notes) if notes else "") if provenance else ("\n".join(notes) or None)
    return _wrap("\n".join(out), env=env, caption=caption, label=label, font=font, position=position, provenance=prov)


def width_hint(pt: agg.PivotTable, std: str, env: Optional[str], font: Optional[str]) -> Optional[str]:
    """Rough single-column width check. IEEE single column fits ~4 'mean ± std' columns at normal size."""
    if env == "table*":
        return None
    ncols = len(pt.cols) * len(pt.metrics)
    per_col = 1.0 if std == "pm" else (0.8 if std == "small" else 0.6)
    scale = {"small": 0.92, "footnotesize": 0.85, "scriptsize": 0.75}.get(font or "", 1.0)
    load = ncols * per_col * scale
    if load <= 4.2:
        return None
    return (f"{ncols} value columns will likely overflow a single IEEE column. Remedies, in order: "
            "drop a metric, use std='small' or 'none', font='footnotesize', split by dataset, or env='table*'.")


def default_comparison_caption(pt: agg.PivotTable, defs: MetricDefs, std: str, underline_second: bool) -> str:
    metrics = ", ".join(metric_header(m, defs, arrows=False) for m in pt.metrics)
    where = ""
    if pt.col_key and pt.cols != [None]:
        where = f" on {', '.join(latex_escape(c) for c in pt.cols)}"
    ns = sorted(pt.n_values())
    if not ns:
        agg_txt = ""
    elif len(ns) == 1:
        agg_txt = f" Mean{' $\\pm$ std' if std != 'none' and ns[0] > 1 else ''} over $n={ns[0]}$ runs per cell."
    else:
        agg_txt = f" Mean{' $\\pm$ std' if std != 'none' else ''} over $n={ns[0]}$--{ns[-1]} runs per cell."
    hl = " Best in bold" + (", second best underlined." if underline_second else ".")
    arrows = " Arrows give the direction of improvement."
    return f"{metrics} by {pt.row_key}{where}.{agg_txt}{hl}{arrows}"


# --------------------------------------------------------------------------- ablation

def ablation_latex(
    rows: Sequence[agg.AblationRow],
    metrics: Sequence[str],
    defs: MetricDefs,
    *,
    caption: Optional[str] = None,
    label: Optional[str] = None,
    env: Optional[str] = "table",
    position: str = "!t",
    font: Optional[str] = None,
    std: str = "pm",
    show_delta: bool = True,
    setting_columns: bool = True,
    setting_names: Optional[Mapping[str, str]] = None,
    metric_names: Optional[Mapping[str, str]] = None,
    base_label: str = "Full model",
    provenance: Optional[str] = None,
) -> str:
    """Variant rows with one column per ablated setting (\\checkmark / $\\times$ / value) and metric columns.

    Best per metric column in bold (ranked before rounding). Deltas are relative to the full model.
    """
    keys = sorted({k for r in rows for k in r.diff}) if setting_columns else []
    base_vals: dict[str, Any] = {}
    for k in keys:
        base_vals[k] = next(r.diff[k][0] for r in rows if k in r.diff)

    def setting_cell(v: Any) -> str:
        if v is True:
            return "\\checkmark"
        if v is False:
            return "$\\times$"
        if v is None:
            return "--"
        return latex_escape(v)

    ranks = {
        m: agg.rank_values([(r.stats[m].mean, i) for i, r in enumerate(rows) if r.stats.get(m) is not None],
                           defs.get(m, {}).get("higher_is_better", True))
        for m in metrics
    }

    colspec = "l " + "c" * len(keys) + (" " if keys else "") + "c" * len(metrics)
    out = ["\\begin{tabular}{" + colspec + "}", "\\toprule"]
    if keys:
        out.append(f"& \\multicolumn{{{len(keys)}}}{{c}}{{Setting}} & \\multicolumn{{{len(metrics)}}}{{c}}{{Result}} \\\\")
        out.append(f"\\cmidrule(lr){{2-{1 + len(keys)}}} \\cmidrule(lr){{{2 + len(keys)}-{1 + len(keys) + len(metrics)}}}")
    head = ["Variant"] + [latex_escape((setting_names or {}).get(k, k)) for k in keys]
    head += [metric_header(m, defs, metric_names) for m in metrics]
    out.append(" & ".join(head) + " \\\\")
    out.append("\\midrule")
    for i, r in enumerate(rows):
        label_txt = base_label if r.is_base else latex_escape(r.label)
        cells = [label_txt]
        for k in keys:
            cells.append(setting_cell(r.diff[k][1] if k in r.diff else base_vals[k]))
        for m in metrics:
            st = r.stats.get(m)
            fmt = defs.get(m, {}).get("fmt", ".2f")
            s = fmt_stat(st, fmt, std)
            if st is not None:
                s = _highlight(s, ranks[m].get(i) == 1, False, False)
                if show_delta and not r.is_base and r.delta.get(m) is not None:
                    s += f" {{\\scriptsize({fmt_signed(r.delta[m], fmt)})}}"
            cells.append(s)
        out.append(" & ".join(cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]

    if caption is None:
        ns = sorted({r.n for r in rows})
        n_txt = f"$n={ns[0]}$" if len(ns) == 1 else f"$n={ns[0]}$--{ns[-1]}"
        caption = (
            "Ablation of the full model. Each row changes one setting"
            + (" (\\checkmark{} on, $\\times$ off)" if any(isinstance(v, bool) for v in base_vals.values()) else "")
            + f". Mean{' $\\pm$ std' if std != 'none' else ''} over {n_txt} runs per row"
            + ("; parentheses give the change relative to the full model" if show_delta else "")
            + ". Best per column in bold."
        )
    return _wrap("\n".join(out), env=env, caption=caption, label=label, font=font, position=position, provenance=provenance)


# --------------------------------------------------------------------------- sweep

def sweep_latex(
    series_by_group: Mapping[tuple, Sequence[tuple[Any, agg.Stat]]],
    param: str,
    metric: str,
    defs: MetricDefs,
    *,
    caption: Optional[str] = None,
    label: Optional[str] = None,
    env: Optional[str] = "table",
    position: str = "!t",
    font: Optional[str] = None,
    std: str = "pm",
    param_label: Optional[str] = None,
    metric_names: Optional[Mapping[str, str]] = None,
    provenance: Optional[str] = None,
) -> str:
    """Rows = swept values, one column per group (or a single metric column). Best per column in bold."""
    hib = defs.get(metric, {}).get("higher_is_better", True)
    fmt = defs.get(metric, {}).get("fmt", ".2f")
    groups = list(series_by_group)
    xs = sorted({x for s in series_by_group.values() for x, _ in s}, key=lambda x: (isinstance(x, str), x))
    lookups = {g: dict(s) for g, s in series_by_group.items()}
    best = {g: agg.best_sweep_value(list(series_by_group[g]), hib) for g in groups}

    out = ["\\begin{tabular}{l " + "c" * len(groups) + "}", "\\toprule"]
    single = groups == [()]
    if not single:
        out.append(f"& \\multicolumn{{{len(groups)}}}{{c}}{{{metric_header(metric, defs, metric_names)}}} \\\\")
        out.append(f"\\cmidrule(lr){{2-{1 + len(groups)}}}")
    head = [latex_escape(param_label or param)]
    head += [metric_header(metric, defs, metric_names)] if single else [latex_escape(" / ".join(map(str, g))) for g in groups]
    out.append(" & ".join(head) + " \\\\")
    out.append("\\midrule")
    for x in xs:
        cells = [latex_escape(f"{x:g}" if isinstance(x, float) else x)]
        for g in groups:
            st = lookups[g].get(x)
            s = fmt_stat(st, fmt, std)
            if st is not None and best[g] == x:
                s = f"\\textbf{{{s}}}"
            cells.append(s)
        out.append(" & ".join(cells) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    if caption is None:
        ns = sorted({st.n for s in series_by_group.values() for _, st in s})
        n_txt = f"$n={ns[0]}$" if len(ns) == 1 else f"$n={ns[0]}$--{ns[-1]}"
        caption = (f"{metric_header(metric, defs, metric_names, arrows=False)} as a function of "
                   f"{latex_escape(param_label or param)}. Mean{' $\\pm$ std' if std != 'none' else ''} over {n_txt} runs per value. "
                   f"Best in bold ({'higher' if hib else 'lower'} is better).")
    return _wrap("\n".join(out), env=env, caption=caption, label=label, font=font, position=position, provenance=provenance)


# --------------------------------------------------------------------------- selection (tuning) table

def selection_latex(
    selections: Sequence[agg.Selection],
    param: str,
    metric: str,
    group_by: Sequence[str],
    defs: MetricDefs,
    *,
    caption: Optional[str] = None,
    label: Optional[str] = None,
    env: Optional[str] = "table",
    font: Optional[str] = None,
    param_label: Optional[str] = None,
    provenance: Optional[str] = None,
) -> str:
    """Per group: the selected value of `param`, the mean metric it achieves, the grid it was chosen from; a
    dagger marks winners at a grid boundary (the optimum may lie outside the searched range)."""
    fmt = defs.get(metric, {}).get("fmt", ".2f")
    plabel = param_label or latex_escape(param)
    heads = [latex_escape(g) for g in group_by] + [plabel, metric_header(metric, defs), "grid"]
    lines = []
    for s in selections:
        cells = [latex_escape(v) for v in s.group]
        cells.append(latex_escape(fmt_number(s.best, "g") if isinstance(s.best, float) else s.best) + ("$^\\dagger$" if s.at_boundary else ""))
        cells.append(fmt_stat(s.stat, fmt))
        cells.append(latex_escape(", ".join(fmt_number(x, "g") if isinstance(x, float) else str(x) for x in s.grid)))
        lines.append(" & ".join(cells) + " \\\\")
    body = "\n".join(["\\toprule", " & ".join(heads) + " \\\\", "\\midrule", *lines, "\\bottomrule"])
    if caption is None:
        caption = (f"Selected {plabel} per {', '.join(latex_escape(g) for g in group_by) or 'setting'}: the value with the best mean "
                   f"{display_metric_name(metric)} over the searched grid. $^\\dagger$ selected at a grid boundary.")
    col_spec = "l" * len(group_by) + "ccl"
    return _wrap(f"\\begin{{tabular}}{{{col_spec}}}\n{body}\n\\end{{tabular}}", caption=caption, label=label, env=env, font=font,
                 position="!t", provenance=provenance)
